import CryptoKit
import Foundation
import Vision

/// My Clutter module: Large & Old Files, Duplicates, Similar Images, Downloads.
public struct ClutterEngine: ScanEngine {
    public let root: URL
    public init(root: URL = Paths.home) { self.root = root }

    public func scan(progress: @escaping @Sendable (String) -> Void) async -> [ResultGroup] {
        progress("Indexing \(Paths.abbreviate(root))")
        let files = Self.index(root)
        progress("Large and old files")
        let large = Self.largeAndOld(files)
        progress("Duplicates")
        let dups = Self.duplicates(files)
        progress("Similar images")
        let similar = Self.similarImages(files)
        progress("Downloads")
        let downloads = Self.downloads()
        return [large, dups, similar, downloads].filter { !$0.isEmpty }
    }

    public struct FileInfo: Sendable { public let url: URL; public let size: Int64; public let modified: Date; public let accessed: Date }

    /// Build output and dependency folders: regenerated by tools, never "clutter" to review file by file.
    static let generatedFolders: Set<String> = [
        "node_modules", "target", "build", "dist", "DerivedData", "Pods", "vendor", "venv", ".venv",
        "__pycache__", ".gradle", ".next", ".nuxt", ".dart_tool", ".build", "intermediates",
    ]

    /// Regular files under `root`, skipping hidden files, packages, ~/Library, source repositories
    /// (folders with a `.git`) and generated build folders — the same user-file scope as My Clutter.
    public static func index(_ root: URL) -> [FileInfo] {
        let keys: [URLResourceKey] = [.isRegularFileKey, .isDirectoryKey, .totalFileAllocatedSizeKey, .contentModificationDateKey, .contentAccessDateKey]
        guard let e = FileManager.default.enumerator(at: root, includingPropertiesForKeys: keys,
                                                     options: [.skipsHiddenFiles, .skipsPackageDescendants],
                                                     errorHandler: { _, _ in true }) else { return [] }
        let skip = Paths.library.path
        let fm = FileManager.default
        var out: [FileInfo] = []
        for case let u as URL in e {
            guard let v = try? u.resourceValues(forKeys: Set(keys)) else { continue }
            if v.isDirectory == true {
                if u.path == skip || generatedFolders.contains(u.lastPathComponent)
                    || fm.fileExists(atPath: u.appendingPathComponent(".git").path) { e.skipDescendants() }
                continue
            }
            guard v.isRegularFile == true else { continue }
            out.append(FileInfo(url: u, size: Int64(v.totalFileAllocatedSize ?? 0),
                                modified: v.contentModificationDate ?? .distantPast,
                                accessed: v.contentAccessDate ?? v.contentModificationDate ?? .distantPast))
        }
        return out
    }

    public static func largeAndOld(_ files: [FileInfo], minSize: Int64 = 50_000_000) -> ResultGroup {
        let yearAgo = Date().addingTimeInterval(-365 * 86_400)
        let items = files.filter { $0.size >= minSize }.sorted { $0.size > $1.size }.prefix(300).map { f in
            let old = f.accessed < yearAgo
            return ResultItem.file(f.url, size: f.size,
                                   subtitle: "\(Paths.abbreviate(f.url.deletingLastPathComponent())) · opened \(RelativeDateTimeFormatter().localizedString(for: f.accessed, relativeTo: Date()))",
                                   selected: false, badge: old ? "Old" : nil)
        }
        return ResultGroup(id: "large-old", title: "Large & Old Files",
                           description: "Files over 50 MB, the biggest first. Files not opened for a year are marked Old.",
                           symbol: "doc.badge.ellipsis", items: Array(items), verb: "to review")
    }

    /// Same size → same hash of the first 64 KB → same full SHA-256. The newest copy is kept.
    public static func duplicates(_ files: [FileInfo], minSize: Int64 = 100_000) -> ResultGroup {
        let bySize = Dictionary(grouping: files.filter { $0.size >= minSize }, by: \.size).values.filter { $0.count > 1 }
        var items: [ResultItem] = []
        for group in bySize {
            let byHead = Dictionary(grouping: group) { hash($0.url, limit: 65_536) ?? UUID().uuidString }.values.filter { $0.count > 1 }
            for g in byHead {
                let byFull = Dictionary(grouping: g) { hash($0.url, limit: nil) ?? UUID().uuidString }.values.filter { $0.count > 1 }
                for set in byFull {
                    let sorted = set.sorted { $0.modified > $1.modified }
                    let keep = sorted[0].url
                    // Only copies in Downloads are preselected ("Duplicate Downloads" in Smart Care).
                    let downloads = Paths.home("Downloads").path + "/"
                    for f in sorted.dropFirst() {
                        items.append(.file(f.url, size: f.size, subtitle: "Copy of \(Paths.abbreviate(keep))",
                                           selected: f.url.path.hasPrefix(downloads)))
                    }
                }
            }
        }
        return ResultGroup(id: "duplicates", title: "Duplicates",
                           description: "Identical copies of the same file. The most recent copy is kept.",
                           symbol: "doc.on.doc", items: items.sorted { ($0.size ?? 0) > ($1.size ?? 0) }, verb: "to remove")
    }

    static func hash(_ url: URL, limit: Int?) -> String? {
        guard let h = try? FileHandle(forReadingFrom: url) else { return nil }
        defer { try? h.close() }
        var hasher = SHA256()
        var remaining = limit ?? Int.max
        while remaining > 0, let chunk = try? h.read(upToCount: min(1 << 20, remaining)), !chunk.isEmpty {
            hasher.update(data: chunk); remaining -= chunk.count
        }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }

    /// Vision feature prints; pairs closer than `threshold` are grouped. Keeps the largest image.
    public static func similarImages(_ files: [FileInfo], threshold: Float = 0.35, limit: Int = 1500) -> ResultGroup {
        let exts: Set<String> = ["jpg", "jpeg", "png", "heic", "tiff", "webp"]
        let images = files.filter { exts.contains($0.url.pathExtension.lowercased()) && $0.size > 20_000 }
            .sorted { $0.modified > $1.modified }.prefix(limit)
        var prints: [(FileInfo, VNFeaturePrintObservation)] = []
        for f in images {
            let req = VNGenerateImageFeaturePrintRequest()
            guard (try? VNImageRequestHandler(url: f.url).perform([req])) != nil,
                  let obs = req.results?.first else { continue }
            prints.append((f, obs))
        }
        var used = Set<Int>()
        var items: [ResultItem] = []
        for i in prints.indices where !used.contains(i) {
            var cluster = [i]
            for j in prints.indices where j > i && !used.contains(j) {
                var d: Float = 0
                if (try? prints[i].1.computeDistance(&d, to: prints[j].1)) != nil, d < threshold { cluster.append(j) }
            }
            guard cluster.count > 1 else { continue }
            used.formUnion(cluster)
            let ordered = cluster.sorted { prints[$0].0.size > prints[$1].0.size }
            let keep = prints[ordered[0]].0.url
            for k in ordered.dropFirst() {
                let f = prints[k].0
                items.append(.file(f.url, size: f.size, subtitle: "Similar to \(keep.lastPathComponent)", selected: false))
            }
        }
        return ResultGroup(id: "similar", title: "Similar Images",
                           description: "Photos that look nearly the same, such as bursts and edits. The largest one is kept.",
                           symbol: "photo.on.rectangle", items: items, verb: "to review")
    }

    /// Downloads grouped by the app they came from (Spotlight `kMDItemWhereFroms`), older than 30 days.
    public static func downloads() -> ResultGroup {
        let monthAgo = Date().addingTimeInterval(-30 * 86_400)
        let items = Paths.children(Paths.home("Downloads")).compactMap { u -> ResultItem? in
            let v = try? u.resourceValues(forKeys: [.contentModificationDateKey, .addedToDirectoryDateKey])
            let date = v?.addedToDirectoryDate ?? v?.contentModificationDate ?? Date()
            guard date < monthAgo else { return nil }
            return .file(u, subtitle: "\(source(of: u)) · \(RelativeDateTimeFormatter().localizedString(for: date, relativeTo: Date()))", selected: false)
        }
        return ResultGroup(id: "downloads", title: "Downloads",
                           description: "Files downloaded more than a month ago.", symbol: "arrow.down.circle",
                           items: items.sorted { ($0.size ?? 0) > ($1.size ?? 0) }, verb: "to review")
    }

    static func source(of url: URL) -> String {
        guard let md = MDItemCreateWithURL(nil, url as CFURL),
              let froms = MDItemCopyAttribute(md, kMDItemWhereFroms) as? [String], let first = froms.first else { return "Downloads" }
        if first.contains("slack") { return "Slack" }
        return URL(string: first)?.host ?? "Downloads"
    }
}
